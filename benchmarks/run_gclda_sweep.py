#!/usr/bin/env python
"""Run Rust GCLDA training over several topic counts on a full meta-analytic corpus.

Runs one ``gclda-train`` process per topic count, a bounded number of them at a
time, and reports wall-clock time per run. Defaults match the requested
configuration: topic counts 50/100/200/400, 5000 iterations, 8 threads per
process, 2 processes at a time (16 cores in use).

Runs are scheduled **longest first**. With four jobs and two slots that matters:
in submission order (50, 100, 200, 400) the two long runs land in the same wave
and the makespan is set by 200+400 back to back, whereas longest-first starts
400 and 200 together and backfills the short runs as slots free. On the
estimates below that is roughly a 3-4 hour difference in total wall time.

Already-finished runs are skipped (a run counts as finished when its output
directory contains ``model.json``), so the script can be re-run after an
interruption without repeating work. Pass ``--force`` to redo them.

CORPUS
------
GCLDA needs raw integer word counts.

**NeuroQuery (default) publishes real counts** -- ``type-count`` feature files
over a 7,547-term vocabulary built from abstracts. This is a scientifically
usable GCLDA corpus and needs no stand-in: 13,459 studies, 469,260 peaks,
1,157,059 word tokens.

**Neurosynth does not.** It ships tf-idf weights, and the cached download
carries no abstracts, so counts cannot be regenerated from text. NiMARE's own
GCLDA example says as much: "GCLDA uses raw word counts instead of the tf-idf
values generated by Neurosynth." Selecting ``--corpus neurosynth`` therefore
also requires ``--allow-tfidf-proxy``, which substitutes ``round(tfidf * 100)``
-- the stand-in the timing benchmarks use. It reproduces a realistic vocabulary
size and sparsity pattern and is fine for measuring speed, but the topics it
produces are **not a scientifically meaningful model**.

``--counts``/``--coordinates`` override either path with TSVs you supply.
"""

import argparse
import json
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import timedelta
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_BINARY = REPO_ROOT / "rust" / "gclda" / "target" / "release" / "gclda-train"

# Per-iteration seconds at T=100, measured on this machine against the
# Neurosynth tf-idf-proxy corpus. Each phase is scaled below by how the target
# corpus differs in the quantity that phase actually iterates over, because the
# corpora differ enormously in one of them: real NeuroQuery abstract counts hold
# 1.16M word tokens against the proxy's 9.73M, and word sampling is O(tokens).
_REF = {
    "word": 1.183,  # O(word tokens x T)
    "peak_seq": 0.837,  # O(peaks x T x R), sequential
    "peak_pdf": 0.511,  # O(peaks x T x R), parallel
    "loglik": 0.076,  # O(nnz x T), amortized at loglikely_freq=10
    "region": 0.004,
}
_REF_CORPUS = {"wtokens": 9_729_860, "peaks": 507_891, "nnz": 1_049_300}
# Two concurrent processes contend for memory bandwidth and shared L3; the
# sequential samplers are the bandwidth-hungry part. Modest, not measured.
_CONTENTION = 1.15


def estimate_seconds(n_topics, n_iters, threads, concurrent_jobs, stats, loglikely_freq):
    """Rough wall-clock estimate for one run. Extrapolated, not measured."""
    scale = n_topics / 100.0
    w = stats["n_wtokens"] / _REF_CORPUS["wtokens"]
    pk = stats["n_peaks"] / _REF_CORPUS["peaks"]
    nz = stats["nnz"] / _REF_CORPUS["nnz"]
    par_speedup = max(1.0, threads * 0.6)

    per_iter = (
        _REF["word"] * scale * w
        + _REF["peak_seq"] * scale * pk
        + (_REF["peak_pdf"] * scale * pk) / par_speedup
        + _REF["loglik"] * scale * nz * (10.0 / max(loglikely_freq, 1))
        + _REF["region"]
    )
    if concurrent_jobs > 1:
        per_iter *= _CONTENTION
    return per_iter * n_iters


def human(seconds):
    return str(timedelta(seconds=int(seconds)))


def _corpus_stats(count_df, coordinates_df):
    import numpy as np

    arr = count_df.to_numpy()
    return {
        "n_docs": int(count_df.shape[0]),
        "n_terms": int(count_df.shape[1]),
        "n_peaks": int(len(coordinates_df)),
        "n_wtokens": int(arr.sum()),
        "nnz": int((arr > 0).sum()),
    }


def _load_neuroquery(vocab, source, data_dir):
    """Build (count_df, coordinates_df) from NeuroQuery's real integer counts."""
    import numpy as np
    import pandas as pd
    import scipy.sparse as sp

    from nimare.extract import fetch_neuroquery

    found = fetch_neuroquery(
        data_dir=data_dir, version="1", source=source, vocab=vocab,
        type="count", return_type="files",
    )
    entry = found[0]
    feat = entry["features"][0]

    matrix = sp.load_npz(feat["features"])
    with open(feat["vocabulary"], encoding="utf-8") as fo:
        terms = [line.strip() for line in fo if line.strip()]
    metadata = pd.read_csv(entry["metadata"], sep="\t")

    if len(metadata) != matrix.shape[0]:
        sys.exit(
            f"NeuroQuery metadata rows ({len(metadata)}) do not match feature rows "
            f"({matrix.shape[0]}); refusing to guess the alignment."
        )

    ids = metadata["id"].astype(str).tolist()
    # int32 halves the dense intermediate; values top out around 29.
    count_df = pd.DataFrame(matrix.toarray().astype(np.int32), index=ids, columns=terms)

    coordinates_df = pd.read_csv(entry["coordinates"], sep="\t")
    coordinates_df["id"] = coordinates_df["id"].astype(str)
    coordinates_df = coordinates_df[["id", "x", "y", "z"]]
    return count_df, coordinates_df


def _load_neurosynth_proxy(allow_proxy, data_dir):
    if not allow_proxy:
        sys.exit(
            "--corpus neurosynth requires --allow-tfidf-proxy.\n\n"
            "Neurosynth ships tf-idf weights, not counts, and the cached download has\n"
            "no abstracts, so real counts cannot be built here. The proxy is\n"
            "round(tfidf * 100): fine for timing, NOT a scientifically meaningful\n"
            "model. Prefer --corpus neuroquery, which publishes real counts."
        )
    sys.path.insert(0, str(REPO_ROOT / "benchmarks"))
    from bench_gclda_rust import load_neurosynth_corpus

    count_df, coordinates_df, meta = load_neurosynth_corpus(timeout=60, data_dir=data_dir)
    if count_df is None:
        sys.exit(f"Neurosynth unavailable: {meta.get('reason', 'unknown')}")
    return count_df, coordinates_df


def stage_corpus(args, stage_dir):
    """Write counts.tsv / coordinates.tsv and return (counts, coords, stats)."""
    from nimare.annotate.gclda_rs import export_gclda_tsvs

    counts_path = stage_dir / "counts.tsv"
    coords_path = stage_dir / "coordinates.tsv"
    stats_path = stage_dir / "corpus_stats.json"

    if args.counts and args.coordinates:
        import pandas as pd

        counts_path, coords_path = Path(args.counts), Path(args.coordinates)
        print(f"Using supplied corpus: {counts_path}")
        cdf = pd.read_csv(counts_path, sep="\t", index_col=0)
        xdf = pd.read_csv(coords_path, sep="\t", float_precision="round_trip")
        return counts_path, coords_path, _corpus_stats(cdf, xdf)

    if counts_path.exists() and coords_path.exists() and stats_path.exists():
        print(f"Reusing staged corpus in {stage_dir}")
        with open(stats_path, encoding="utf-8") as fo:
            return counts_path, coords_path, json.load(fo)

    if args.corpus == "neuroquery":
        print(f"Staging NeuroQuery ({args.nq_vocab}, source={args.nq_source}, real counts) ...")
        count_df, coordinates_df = _load_neuroquery(
            args.nq_vocab, args.nq_source, args.neurosynth_data_dir
        )
    else:
        print("Staging Neurosynth (tf-idf PROXY counts -- timing only) ...")
        count_df, coordinates_df = _load_neurosynth_proxy(
            args.allow_tfidf_proxy, args.neurosynth_data_dir
        )

    stage_dir.mkdir(parents=True, exist_ok=True)
    counts_path, coords_path = export_gclda_tsvs(count_df, coordinates_df, str(stage_dir))
    stats = _corpus_stats(count_df, coordinates_df)
    stats["corpus"] = args.corpus
    with open(stats_path, "w", encoding="utf-8") as fo:
        json.dump(stats, fo, indent=2)
    print(
        f"  {stats['n_docs']:,} documents x {stats['n_terms']:,} terms, "
        f"{stats['n_peaks']:,} peaks, {stats['n_wtokens']:,} word tokens"
    )
    return Path(counts_path), Path(coords_path), stats


def run_one(binary, counts, coords, mask, out_root, n_topics, args, stats):
    out_dir = out_root / f"topics-{n_topics:03d}"
    log_path = out_root / f"topics-{n_topics:03d}.log"

    if (out_dir / "model.json").exists() and not args.force:
        print(f"[T={n_topics}] SKIP (already complete)")
        return {"n_topics": n_topics, "status": "skipped", "seconds": 0.0}

    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = [
        str(binary),
        "--counts", str(counts),
        "--coordinates", str(coords),
        "--mask", str(mask),
        "--out-dir", str(out_dir),
        "--n-topics", str(n_topics),
        "--n-regions", str(args.n_regions),
        "--symmetric", "true" if args.symmetric else "false",
        "--n-iters", str(args.n_iters),
        "--loglikely-freq", str(args.loglikely_freq),
        "--seed-init", str(args.seed_init),
        "--threads", str(args.threads),
    ]
    if args.peak_block_size is not None:
        cmd += ["--peak-block-size", str(args.peak_block_size)]

    est = estimate_seconds(
        n_topics, args.n_iters, args.threads, args.jobs, stats, args.loglikely_freq
    )
    print(f"[T={n_topics}] START  (rough estimate {human(est)})  -> {log_path}")

    start = time.time()
    with open(log_path, "w", encoding="utf-8") as log:
        log.write(" ".join(cmd) + "\n\n")
        log.flush()
        completed = subprocess.run(cmd, stdout=log, stderr=subprocess.STDOUT)
    elapsed = time.time() - start

    status = "ok" if completed.returncode == 0 else f"FAILED(rc={completed.returncode})"
    print(f"[T={n_topics}] {status}  in {human(elapsed)}")
    return {
        "n_topics": n_topics,
        "status": status,
        "seconds": elapsed,
        "out_dir": str(out_dir),
        "log": str(log_path),
    }


def parse_args():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--topics", type=int, nargs="+", default=[50, 100, 200, 400])
    p.add_argument("--n-iters", type=int, default=5000)
    p.add_argument("--threads", type=int, default=8, help="Rayon threads per process.")
    p.add_argument("--jobs", type=int, default=2, help="Processes to run at once.")
    p.add_argument("--n-regions", type=int, default=2)
    p.add_argument("--symmetric", action=argparse.BooleanOptionalAction, default=True)
    p.add_argument(
        "--loglikely-freq",
        type=int,
        default=50,
        help="50 gives 100 trace points over 5000 iterations at ~1%% of runtime. "
        "Higher is marginally faster but leaves no convergence trace.",
    )
    p.add_argument("--seed-init", type=int, default=1)
    p.add_argument(
        "--peak-block-size",
        type=int,
        default=None,
        help="Omit to let gclda-train size the block from its byte budget.",
    )
    p.add_argument(
        "--corpus",
        choices=["neuroquery", "neurosynth"],
        default="neuroquery",
        help="neuroquery (default) publishes real integer counts; neurosynth only has "
        "tf-idf and needs --allow-tfidf-proxy.",
    )
    p.add_argument(
        "--nq-vocab",
        default="neuroquery7547",
        help="NeuroQuery vocabulary. neuroquery156521 is also published but makes the "
        "W x T count matrix ~20x larger for little topical gain.",
    )
    p.add_argument(
        "--nq-source",
        default="abstract",
        choices=["abstract", "body", "title", "keywords"],
        help="Which text NeuroQuery counted. 'body' is full text: far more tokens and "
        "proportionally slower word sampling.",
    )
    p.add_argument("--counts", default=None, help="Path to a counts TSV you trust.")
    p.add_argument("--coordinates", default=None, help="Path to a coordinates TSV.")
    p.add_argument(
        "--allow-tfidf-proxy",
        action="store_true",
        help="Permit round(tfidf * 100) stand-in counts. Timing only -- see module docstring.",
    )
    p.add_argument("--neurosynth-data-dir", default=None)
    p.add_argument("--mask", default=None)
    p.add_argument("--out-root", default=str(REPO_ROOT / "gclda_runs"))
    p.add_argument("--stage-dir", default=None)
    p.add_argument("--binary", default=str(DEFAULT_BINARY))
    p.add_argument("--force", action="store_true", help="Re-run completed configurations.")
    p.add_argument("--dry-run", action="store_true", help="Print the plan and exit.")
    return p.parse_args()


def main():
    args = parse_args()

    binary = Path(args.binary)
    if not binary.exists():
        sys.exit(f"gclda-train not found at {binary}\nBuild it: cd rust/gclda && cargo build --release")

    if args.mask:
        mask = Path(args.mask)
    else:
        from nimare.utils import get_resource_path

        mask = Path(get_resource_path()) / "templates" / "MNI152_2x2x2_brainmask.nii.gz"

    out_root = Path(args.out_root)
    out_root.mkdir(parents=True, exist_ok=True)
    stage_dir = Path(args.stage_dir) if args.stage_dir else out_root / "corpus"

    # Longest first: with fewer slots than jobs, this minimizes total wall time.
    topics = sorted(args.topics, reverse=True)
    total_cores = args.threads * args.jobs

    counts, coords, stats = stage_corpus(args, stage_dir)

    print("=" * 72)
    print(f"GCLDA sweep on {stats.get('corpus', args.corpus)}: "
          f"topics={sorted(args.topics)}  n_iters={args.n_iters}")
    print(f"corpus: {stats['n_docs']:,} docs x {stats['n_terms']:,} terms, "
          f"{stats['n_peaks']:,} peaks, {stats['n_wtokens']:,} word tokens")
    print(f"{args.jobs} concurrent process(es) x {args.threads} threads = {total_cores} cores")
    print(f"Run order (longest first): {topics}")
    print(f"Outputs: {out_root}")
    print("=" * 72)
    for t in topics:
        est = estimate_seconds(t, args.n_iters, args.threads, args.jobs, stats, args.loglikely_freq)
        print(f"  T={t:<4} rough estimate {human(est)}")
    slots = [0.0] * args.jobs
    for t in topics:
        i = slots.index(min(slots))
        slots[i] += estimate_seconds(
            t, args.n_iters, args.threads, args.jobs, stats, args.loglikely_freq
        )
    print(f"  TOTAL wall-clock estimate: ~{human(max(slots))}")
    print("  (extrapolated from a 20-iteration measurement; treat as +/-30%)")
    print("=" * 72)

    if args.dry_run:
        print("\n--dry-run: not launching.")
        return

    started = time.time()
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        results = list(
            pool.map(
                lambda t: run_one(binary, counts, coords, mask, out_root, t, args, stats),
                topics,
            )
        )
    total = time.time() - started

    print("\n" + "=" * 72)
    print(f"{'topics':>8}{'status':>14}{'wall clock':>16}")
    for r in sorted(results, key=lambda r: r["n_topics"]):
        print(f"{r['n_topics']:>8}{r['status']:>14}{human(r['seconds']):>16}")
    print(f"\nTotal wall clock: {human(total)}")
    print("=" * 72)

    manifest = {
        "config": vars(args),
        "mask": str(mask),
        "counts": str(counts),
        "coordinates": str(coords),
        "corpus_stats": stats,
        "total_seconds": total,
        "runs": results,
    }
    with open(out_root / "run_manifest.json", "w", encoding="utf-8") as fo:
        json.dump(manifest, fo, indent=2, default=str)
    print(f"Manifest: {out_root / 'run_manifest.json'}")

    if any(r["status"].startswith("FAILED") for r in results):
        sys.exit(1)


if __name__ == "__main__":
    main()
